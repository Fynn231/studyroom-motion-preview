import { test } from 'node:test';
import assert from 'node:assert/strict';
import React from 'react';
import { JSDOM } from 'jsdom';
import { App } from '../src/App.js';
import { PRESETS } from '../src/Appearance.js';

test('ten labeled preview presets include private Juliette flowers with explicit bounded on/off and cleanup', async t => {
  const dom = new JSDOM('<!doctype html><html><body></body></html>', { url: 'http://localhost' });
  Object.assign(globalThis, { window: dom.window, document: dom.window.document, HTMLElement: dom.window.HTMLElement, IS_REACT_ACT_ENVIRONMENT: true });
  const { render, fireEvent, within, cleanup } = await import('@testing-library/react');
  t.after(() => { cleanup(); dom.window.close(); });
  const activeVisibility = new Set<unknown>();
  const add = dom.window.document.addEventListener.bind(dom.window.document);
  const remove = dom.window.document.removeEventListener.bind(dom.window.document);
  dom.window.document.addEventListener = ((type: string, listener: EventListenerOrEventListenerObject, options?: boolean | AddEventListenerOptions) => {
    if (type === 'visibilitychange') activeVisibility.add(listener);
    add(type, listener, options);
  }) as typeof dom.window.document.addEventListener;
  dom.window.document.removeEventListener = ((type: string, listener: EventListenerOrEventListenerObject, options?: boolean | EventListenerOptions) => {
    if (type === 'visibilitychange') activeVisibility.delete(listener);
    remove(type, listener, options);
  }) as typeof dom.window.document.removeEventListener;
  const view = render(<App />), q = within(view.container);
  fireEvent.click(q.getByText('Appearance', { selector: 'summary' }));
  assert.equal(PRESETS.length, 10);
  assert.equal(view.container.querySelectorAll('.preset-swatch').length, 10);
  const timer = q.getByRole('timer'), draft = q.getByLabelText('Your session intention');
  fireEvent.change(draft, { target: { value: 'Synthetic flowers draft' } });
  fireEvent.click(q.getByRole('button', { name: 'Start focus' }));
  fireEvent.click(q.getByRole('button', { name: 'Juliette' }));
  const layer = view.container.querySelector<HTMLElement>('.flower-layer')!;
  assert.ok(layer); assert.equal(layer.getAttribute('aria-hidden'), 'true');
  assert.equal(activeVisibility.size, 1);
  assert.equal(layer.querySelectorAll('svg').length, 24);
  const flowers = [...layer.querySelectorAll<SVGElement>('svg')];
  assert.equal(new Set(flowers.map(f => f.style.getPropertyValue('--rest'))).size, 24, 'nonuniform scattered resting heights');
  assert.ok(new Set(flowers.map(f => f.style.getPropertyValue('--x'))).size >= 18, 'scattered across the background, not repeated edge rows');
  assert.ok(flowers.every(f => { const seconds = parseFloat(f.style.getPropertyValue('--duration')); return seconds >= 24 && seconds <= 42; }));
  assert.equal(layer.querySelectorAll('a, button, input, [tabindex]').length, 0);
  const toggle = q.getByLabelText('Falling flowers') as HTMLInputElement;
  assert.equal(toggle.checked, false); assert.equal(layer.dataset.falling, 'false');
  fireEvent.click(toggle); assert.equal(layer.dataset.falling, 'true');
  Object.defineProperty(dom.window.document, 'hidden', { configurable: true, value: true });
  fireEvent(dom.window.document, new dom.window.Event('visibilitychange'));
  assert.equal(layer.dataset.paused, 'true');
  Object.defineProperty(dom.window.document, 'hidden', { configurable: true, value: false });
  fireEvent(dom.window.document, new dom.window.Event('visibilitychange'));
  assert.equal(layer.dataset.paused, 'false');
  fireEvent.click(toggle); assert.equal(layer.dataset.falling, 'false');
  fireEvent.click(toggle);
  fireEvent.click(q.getByRole('button', { name: 'Ocean Haze' }));
  assert.equal(view.container.querySelector('.flower-layer'), null);
  assert.equal(activeVisibility.size, 0, 'leaving removes the actual registered visibility listener');
  fireEvent.click(q.getByRole('button', { name: 'Juliette' }));
  assert.equal((q.getByLabelText('Falling flowers') as HTMLInputElement).checked, false);
  fireEvent.click(q.getByLabelText('Falling flowers'));
  fireEvent.change(q.getByLabelText('First custom HEX'), { target: { value: 'url(unsafe)' } });
  assert.ok(view.container.querySelector('.flower-layer'), 'invalid entry retains the whole last valid theme');
  fireEvent.change(q.getByLabelText('First custom HEX'), { target: { value: '#000000' } });
  assert.equal(view.container.querySelector('.flower-layer'), null);
  fireEvent.click(q.getByRole('button', { name: 'Juliette' }));
  fireEvent.click(q.getByRole('button', { name: 'Reset appearance to white and sage' }));
  assert.equal(view.container.querySelector('.flower-layer'), null);
  assert.equal(q.getByRole('timer'), timer); assert.equal(q.getByLabelText('Your session intention'), draft);
  assert.equal((draft as HTMLTextAreaElement).value, 'Synthetic flowers draft');
  assert.ok(q.getByRole('button', { name: 'Pause focus' }));
  assert.equal(dom.window.localStorage.length, 0);
  fireEvent.click(q.getByRole('button', { name: 'Juliette' }));
  assert.equal(activeVisibility.size, 1);
  view.unmount();
  assert.equal(activeVisibility.size, 0);
  // A fresh view never inherits another instance's palette/effects.
  const fresh = render(<App />);
  assert.equal(fresh.container.querySelector('.flower-layer'), null);
  assert.equal(fresh.container.querySelector<HTMLElement>('.room-backdrop')!.style.background, '');
});
