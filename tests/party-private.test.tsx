import { test } from 'node:test';
import assert from 'node:assert/strict';
import React from 'react';
import { JSDOM } from 'jsdom';
import { io, type Socket } from 'socket.io-client';
import { createStudyServer } from '../server/app.js';
import { App } from '../src/App.js';
import type { Reply, RoomState } from '../src/protocol.js';

test('real Party peers never receive private clocks, music, reflection or history; leaving and changing rooms do not reshare', async t => {
  const dom = new JSDOM('<!doctype html><html><body></body></html>', { url: 'http://localhost' });
  Object.assign(globalThis, { window: dom.window, document: dom.window.document, HTMLElement: dom.window.HTMLElement, IS_REACT_ACT_ENVIRONMENT: true });
  const { render, fireEvent, waitFor, within, cleanup } = await import('@testing-library/react');
  const app = createStudyServer(); const endpoint = await app.listen(0); const sockets: Socket[] = [];
  t.after(async () => { cleanup(); sockets.forEach(s => s.disconnect()); await app.close(); dom.window.close(); });
  async function peer() {
    const socket = io(endpoint, { forceNew: true, reconnection: false }); sockets.push(socket);
    await new Promise<void>((resolve, reject) => { socket.once('connect', resolve); socket.once('connect_error', reject); });
    return socket;
  }
  const request = async (s: Socket, event: string, data: object) => {
    const reply: Reply = await s.timeout(2000).emitWithAck(event, data); assert.ok(reply.ok); return reply.state;
  };
  const b = await peer(), c = await peer();
  const roomB = await request(b, 'room:create', { name: 'Synthetic Fern' });
  const roomC = await request(c, 'room:create', { name: 'Synthetic Moss' });
  const started = await request(b, 'timer:control', { action: 'start', durationMinutes: 1 });
  const packetsB: RoomState[] = [], packetsC: RoomState[] = [];
  b.on('room:state', state => packetsB.push(state)); c.on('room:state', state => packetsC.push(state));
  const view = render(<App endpoint={endpoint} />); const q = within(view.container);
  fireEvent.change(q.getByLabelText('Your session intention'), { target: { value: 'SYNTHETIC PRIVATE COMMITMENT' } });
  fireEvent.change(q.getByLabelText('Focus length'), { target: { value: '15' } });
  fireEvent.click(q.getByRole('button', { name: 'Start focus' }));
  fireEvent.click(q.getByRole('button', { name: 'Pause focus' }));
  const personal = q.getByRole('timer').textContent;
  async function enter(code: string, fresh = false) {
    fireEvent.click(q.getByRole('button', { name: 'Party' }));
    await waitFor(() => assert.equal((q.getByRole('button', { name: 'Join room' }) as HTMLButtonElement).disabled, false));
    fireEvent.change(q.getByLabelText('Your name'), { target: { value: 'Synthetic Cedar' } });
    fireEvent.change(q.getByLabelText('Invite code'), { target: { value: code } });
    fireEvent.click(q.getByRole('button', { name: 'Join room' }));
    await waitFor(() => assert.equal(q.getByLabelText('Room code').textContent, code));
    assert.equal(q.getByRole('timer').textContent, fresh ? '45:00' : personal, 'fresh private duration previews immediately; joining never changes it or a paused personal cycle');
    assert.equal((q.getByRole('button', { name: fresh ? 'Start focus' : 'Resume focus' }) as HTMLButtonElement).disabled, true, 'explicit clock choice is required');
  }
  await enter(roomB.code);
  fireEvent.click(q.getByRole('button', { name: 'Keep personal clock' }));
  assert.equal((q.getByRole('button', { name: 'Resume focus' }) as HTMLButtonElement).disabled, false);
  await waitFor(() => assert.equal(packetsB.at(-1)?.participants.length, 2));
  const before = packetsB.length;
  fireEvent.click(q.getByRole('button', { name: 'Resume focus' }));
  fireEvent.click(q.getByRole('button', { name: 'Pause focus' }));
  fireEvent.click(q.getByText('Music', { selector: 'summary' }));
  fireEvent.change(q.getByLabelText('Spotify link'), { target: { value: 'https://open.spotify.com/track/0123456789ABCDEFGHIJKL?si=SYNTHETICMUSIC' } });
  fireEvent.click(q.getByRole('button', { name: 'Select music link' }));
  fireEvent.click(q.getByRole('button', { name: 'Join room cycle' }));
  assert.ok(q.getByRole('heading', { name: 'Shared focus' }));
  fireEvent.click(q.getByRole('button', { name: 'Finish privately' }));
  assert.ok(q.getByRole('button', { name: 'Pause focus' }), 'private finish does not pause the displayed room cycle');
  fireEvent.change(q.getByLabelText('Session outcome'), { target: { value: 'blocked' } });
  fireEvent.change(q.getByLabelText('Reflection note (optional)'), { target: { value: 'SYNTHETIC PRIVATE REFLECTION' } });
  fireEvent.click(q.getByRole('button', { name: 'Save private reflection' }));
  fireEvent.click(q.getByText('Private history (1)', { selector: 'summary' }));
  fireEvent.click(q.getByLabelText('Store history on this device'));
  await React.act(async () => { await new Promise(resolve => setTimeout(resolve, 100)); });
  assert.equal(packetsB.length, before, 'private actions must not broadcast room changes');
  assert.equal(packetsC.length, 0, 'other room is isolated');
  assert.equal(JSON.stringify(packetsB).includes('SYNTHETIC PRIVATE'), false);
  assert.equal(JSON.stringify(packetsB).includes('spotify'), false);
  assert.equal(packetsB.at(-1)!.timer.endsAt, started.timer.endsAt);
  fireEvent.click(q.getByRole('button', { name: 'Share with room' }));
  await waitFor(() => assert.equal(packetsB.at(-1)?.participants.find(p => p.name === 'Synthetic Cedar')?.intention, 'SYNTHETIC PRIVATE COMMITMENT'));
  assert.equal(JSON.stringify(packetsB).includes('SYNTHETIC PRIVATE REFLECTION'), false);
  fireEvent.click(q.getByRole('button', { name: 'Solo' }));
  await waitFor(() => assert.equal(packetsB.at(-1)?.participants.length, 1));
  assert.equal(packetsB.at(-1)!.timer.endsAt, started.timer.endsAt);
  assert.equal(q.getByRole('timer').textContent, personal);
  assert.ok(q.getByText('SYNTHETIC PRIVATE REFLECTION'));
  assert.ok(q.getByRole('link', { name: 'Open in Spotify (new tab)' }));
  await enter(roomB.code);
  await waitFor(() => assert.equal(packetsB.at(-1)?.participants.length, 2));
  assert.equal(packetsB.at(-1)!.participants.find(p => p.name === 'Synthetic Cedar')?.intention, undefined);
  fireEvent.click(q.getByRole('button', { name: 'Solo' }));
  await waitFor(() => assert.equal(packetsB.at(-1)?.participants.length, 1));
  const bCount = packetsB.length;
  await enter(roomC.code);
  await waitFor(() => assert.equal(packetsC.at(-1)?.participants.length, 2));
  assert.equal(packetsC.at(-1)!.participants.find(p => p.name === 'Synthetic Cedar')?.intention, undefined);
  fireEvent.click(q.getByRole('button', { name: 'Join room cycle' }));
  assert.equal(q.getByRole('timer').textContent, '25:00');
  fireEvent.click(q.getByRole('button', { name: 'Start focus' }));
  await waitFor(() => assert.ok(q.getByRole('button', { name: 'Pause focus' })));
  assert.equal(packetsB.length, bCount, 'controlling another room never touches the former room');
  fireEvent.click(q.getByRole('button', { name: 'Solo' }));
  assert.equal(q.getByRole('timer').textContent, personal);
  assert.equal((q.getByLabelText('Your session intention') as HTMLTextAreaElement).value, 'SYNTHETIC PRIVATE COMMITMENT');
  fireEvent.click(q.getByRole('button', { name: 'Reset timer' }));
  fireEvent.change(q.getByLabelText('Focus length'), { target: { value: '45' } });
  await enter(roomB.code, true);
  assert.equal((q.getByLabelText('Focus length') as HTMLInputElement).value, '45', 'joining must preserve an unstarted personal duration choice');
  fireEvent.click(q.getByRole('button', { name: 'Join room cycle' }));
  assert.equal((q.getByLabelText('Focus length') as HTMLInputElement).value, '1');
  fireEvent.click(q.getByRole('button', { name: 'Keep personal clock' }));
  assert.equal((q.getByLabelText('Focus length') as HTMLInputElement).value, '45');
});
