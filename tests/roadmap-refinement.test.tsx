import { test } from 'node:test';
import assert from 'node:assert/strict';
import React from 'react';
import { JSDOM } from 'jsdom';
import { GoalNotes } from '../src/GoalNotesPanel.js';

test('optional answers change visible session scope and selected next step without losing progress or nagging', async t => {
  const dom = new JSDOM('<html><body></body></html>', { url: 'http://localhost' });
  Object.assign(globalThis, { window: dom.window, document: dom.window.document, HTMLElement: dom.window.HTMLElement, FileReader: dom.window.FileReader, ArrayBuffer: dom.window.ArrayBuffer, IS_REACT_ACT_ENVIRONMENT: true });
  const { render, fireEvent, within, waitFor, cleanup } = await import('@testing-library/react');
  t.after(() => { cleanup(); dom.window.close(); });
  const view = render(<GoalNotes commitment="" onChoose={() => assert.fail('refining is not choosing an intention')} />), q = within(view.container);
  fireEvent.click(q.getByText('Goals / notes', { selector: 'summary' }));
  fireEvent.change(q.getByLabelText('Choose Markdown notes'), { target: { files: [new dom.window.File([Array.from({ length: 7 }, (_, i) => `- [ ] Fictional task ${i + 1}`).join('\n')], 'refine.md')] } });
  await waitFor(() => assert.ok(q.getByText('Fictional task 1')));
  fireEvent.click(q.getByRole('button', { name: 'Build session roadmap' }));
  const panel = within(view.container.querySelector<HTMLElement>('.roadmap-panel')!);
  fireEvent.click(panel.getByRole('checkbox', { name: 'Fictional task 1' }));
  const questions = panel.getByText('Optional: refine this session', { selector: 'summary' });
  assert.equal((questions.parentElement as HTMLDetailsElement).open, false);
  fireEvent.click(questions);
  const lastOption = panel.getByRole('option', { name: /Fictional task 7/ });
  assert.ok(lastOption.textContent!.startsWith('Fictional task 7'), 'task title leads the label so narrow native selects show the meaningful choice');
  fireEvent.change(panel.getByLabelText('How much time do you want to allow?'), { target: { value: '10' } });
  fireEvent.change(panel.getByLabelText('Which step should come next?'), { target: { value: 'file-0:line-7:source' } });
  fireEvent.click(panel.getByRole('button', { name: 'Apply session choices' }));
  assert.equal(panel.getAllByRole('checkbox').length, 3);
  assert.ok(panel.getByRole('checkbox', { name: 'Fictional task 7' }));
  assert.ok(panel.getByText('Your selected next step'));
  assert.ok(panel.getByText(/10-minute scope · showing 3 of 7 steps/));
  assert.ok(panel.getByText('1/7 done'));
  fireEvent.click(panel.getByRole('button', { name: 'Show full roadmap' }));
  assert.equal(panel.getAllByRole('checkbox').length, 7);
  assert.equal((panel.getByRole('checkbox', { name: 'Fictional task 1' }) as HTMLInputElement).checked, true);
  fireEvent.click(panel.getByRole('button', { name: 'Skip refinement questions' }));
  view.rerender(<GoalNotes commitment="changed parent prop" onChoose={() => {}} />);
  assert.equal(q.queryByText('Optional: refine this session'), null, 'dismissal survives rerenders');
  assert.ok(q.getByText('1/7 done'));
});
