import { test } from 'node:test';
import assert from 'node:assert/strict';
import React from 'react';
import { JSDOM } from 'jsdom';
import { App } from '../src/App.js';

test('import → deliberate build → done/undo → private step selection → invalidation', async t => {
  const dom = new JSDOM('<html><body></body></html>', { url: 'http://localhost' });
  Object.assign(globalThis, { window: dom.window, document: dom.window.document, HTMLElement: dom.window.HTMLElement, FileReader: dom.window.FileReader, ArrayBuffer: dom.window.ArrayBuffer, IS_REACT_ACT_ENVIRONMENT: true });
  const { render, fireEvent, within, waitFor, cleanup } = await import('@testing-library/react');
  t.after(() => { cleanup(); dom.window.close(); });
  const view = render(<App />), q = within(view.container);
  fireEvent.click(q.getByText('Goals / notes', { selector: 'summary' }));
  const choose = (name: string, raw: string) => fireEvent.change(q.getByLabelText('Choose Markdown notes'), { target: { files: [new dom.window.File([raw], name)] } });
  choose('synthetic.md', '# Orbit\n- [ ] Sketch a fictional moon\n- [x] Finished moon\n- [ ] Compare craters');
  await waitFor(() => assert.ok(q.getByText('Sketch a fictional moon')));
  assert.equal(q.queryByRole('checkbox', { name: 'Sketch a fictional moon' }), null, 'no automatic plan');
  fireEvent.click(q.getByRole('button', { name: 'Build session roadmap' }));
  const panel = within(view.container.querySelector<HTMLElement>('.roadmap-panel')!);
  const step = panel.getByRole('checkbox', { name: 'Sketch a fictional moon' }) as HTMLInputElement;
  fireEvent.click(step); assert.equal(step.checked, true); assert.ok(panel.getByText('1/2 done'));
  fireEvent.click(step); assert.equal(step.checked, false); assert.ok(panel.getByText('0/2 done'));
  assert.ok(panel.getByText(/synthetic.md · file 1 · Orbit · line 2/));
  assert.equal(panel.queryByText('Finished moon'), null);
  fireEvent.change(q.getByLabelText('Your session intention'), { target: { value: 'Prior intention' } });
  fireEvent.click(panel.getAllByRole('button', { name: 'Replace private intention with this step' })[0]);
  assert.equal((q.getByLabelText('Your session intention') as HTMLTextAreaElement).value, 'Sketch a fictional moon');
  assert.equal(q.getByRole('timer').textContent, '25:00');
  assert.ok(q.getByRole('button', { name: 'Start focus' }));
  assert.equal(dom.window.localStorage.length, 0);
  choose('replacement.md', '# New\n- [ ] Read another fictional page');
  assert.equal(q.queryByRole('checkbox', { name: 'Sketch a fictional moon' }), null);
  await waitFor(() => assert.ok(q.getByText('Read another fictional page')));
  fireEvent.click(q.getByRole('button', { name: 'Build session roadmap' }));
  fireEvent.click(q.getByRole('button', { name: 'Clear imported notes' }));
  assert.equal(view.container.textContent!.includes('replacement.md'), false);
  assert.equal(view.container.querySelector('.roadmap-panel'), null);
  assert.equal((q.getByLabelText('Your session intention') as HTMLTextAreaElement).value, 'Sketch a fictional moon');
});
