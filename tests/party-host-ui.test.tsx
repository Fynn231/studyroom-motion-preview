import { test } from 'node:test';
import assert from 'node:assert/strict';
import React from 'react';
import { JSDOM } from 'jsdom';
import { createStudyServer } from '../server/app.js';
import { App } from '../src/App.js';

test('explicit lobby Enter joins without starting; host admission/removal UI preserves a removed private draft', async t => {
  const dom = new JSDOM('<html><body></body></html>', { url: 'http://localhost' });
  Object.assign(globalThis, { window: dom.window, document: dom.window.document, HTMLElement: dom.window.HTMLElement, IS_REACT_ACT_ENVIRONMENT: true });
  const { render, fireEvent, waitFor, within, cleanup } = await import('@testing-library/react');
  const app = createStudyServer(), endpoint = await app.listen(0);
  t.after(async () => { cleanup(); await app.close(); dom.window.close(); });
  const a = render(<App endpoint={endpoint} />), b = render(<App endpoint={endpoint} />);
  const qa = within(a.container), qb = within(b.container);
  for (const q of [qa, qb]) fireEvent.click(q.getByRole('button', { name: 'Party' }));
  await waitFor(() => assert.equal((qa.getByRole('button', { name: 'Create room' }) as HTMLButtonElement).disabled, false));
  fireEvent.change(qb.getByLabelText('Your name'), { target: { value: 'Guest' } });
  fireEvent.submit(qb.getByLabelText('Your name').closest('form')!);
  await waitFor(() => assert.match(qb.getByRole('alert').textContent!, /six uppercase/i));
  assert.equal(qb.queryAllByLabelText('Room code').length, 0);
  fireEvent.change(qa.getByLabelText('Your name'), { target: { value: 'Host' } });
  fireEvent.click(qa.getByRole('button', { name: 'Create room' }));
  await waitFor(() => assert.ok(qa.getByLabelText('Room code')));
  const code = qa.getByLabelText('Room code').textContent!;
  fireEvent.change(qb.getByLabelText('Your name'), { target: { value: 'Guest' } });
  fireEvent.change(qb.getByLabelText('Invite code'), { target: { value: code } });
  fireEvent.change(qb.getByLabelText('Your session intention'), { target: { value: 'Private surviving draft' } });
  fireEvent.submit(qb.getByLabelText('Your name').closest('form')!);
  await waitFor(() => assert.ok(qb.getByLabelText('Room code')));
  assert.equal(qb.getByRole('timer').textContent, '25:00');
  assert.equal(qb.queryByRole('button', { name: 'Lock admission' }), null);
  fireEvent.click(qa.getByRole('button', { name: 'Lock admission' }));
  await waitFor(() => assert.match(b.container.textContent!, /Admission locked/));
  assert.ok(qb.getByRole('button', { name: 'Join room cycle' }));
  fireEvent.click(qa.getByRole('button', { name: 'Remove Guest' }));
  await waitFor(() => assert.equal(qb.queryAllByLabelText('Room code').length, 0));
  assert.match(qb.getByRole('alert').textContent!, /host removed/i);
  assert.equal((qb.getByLabelText('Your session intention') as HTMLTextAreaElement).value, 'Private surviving draft');
  fireEvent.submit(qb.getByLabelText('Your name').closest('form')!);
  await waitFor(() => assert.match(qb.getByRole('alert').textContent!, /locked/i));
  fireEvent.click(qa.getByRole('button', { name: 'Unlock admission' }));
  await waitFor(() => assert.ok(qa.getByRole('button', { name: 'Lock admission' })));
  fireEvent.submit(qb.getByLabelText('Your name').closest('form')!);
  await waitFor(() => assert.ok(qb.getByLabelText('Room code')));
  assert.equal(a.container.textContent!.includes('Private surviving draft'), false);
});
