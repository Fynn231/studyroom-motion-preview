import { test } from 'node:test';
import assert from 'node:assert/strict';
import React from 'react';
import { JSDOM } from 'jsdom';
import { App } from '../src/App.js';
import { createStudyServer } from '../server/app.js';

test('typed whole minutes accept 37, keep an edit buffer through ticks, reject invalid ranges and lock an in-progress cycle', async t => {
  const dom = new JSDOM('<!doctype html><html><body></body></html>', { url: 'http://localhost' });
  Object.assign(globalThis, { window: dom.window, document: dom.window.document, HTMLElement: dom.window.HTMLElement, IS_REACT_ACT_ENVIRONMENT: true });
  const { render, fireEvent, within, cleanup } = await import('@testing-library/react');
  t.after(() => { cleanup(); dom.window.close(); });
  const view = render(<App />), q = within(view.container);
  const field = q.getByRole('spinbutton', { name: 'Focus length' }) as HTMLInputElement;
  assert.equal(field.type, 'number'); assert.equal(field.inputMode, 'numeric');
  assert.equal(field.min, '1'); assert.equal(field.max, '180'); assert.equal(field.step, '1');
  for (const value of ['', '0', '-1', '181', '1.5', '1e2']) {
    fireEvent.change(field, { target: { value } });
    assert.equal(field.getAttribute('aria-invalid'), 'true', value);
    assert.match(q.getByRole('alert').textContent!, /whole number from 1 to 180 minutes/i);
    assert.equal((q.getByRole('button', { name: 'Start focus' }) as HTMLButtonElement).disabled, true);
    assert.equal(q.getByRole('timer').textContent, '25:00');
  }
  fireEvent.change(field, { target: { value: '' } });
  await React.act(async () => { await new Promise(r => setTimeout(r, 600)); });
  assert.equal(field.value, '', '250ms clock ticks must not replace the editing buffer');
  fireEvent.change(field, { target: { value: '37' } });
  assert.equal(field.getAttribute('aria-invalid'), 'false'); assert.equal(q.queryByRole('alert'), null);
  assert.equal(q.getByRole('timer').textContent, '37:00', 'fresh valid input previews immediately without Start');
  await React.act(async () => { await new Promise(r => setTimeout(r, 600)); });
  assert.equal(q.getByRole('timer').textContent, '37:00', 'preview does not tick');
  fireEvent.click(q.getByRole('button', { name: 'Start focus' }));
  assert.equal(q.getByRole('timer').textContent, '37:00'); assert.equal(field.disabled, true);
  await React.act(async () => { await new Promise(r => setTimeout(r, 1100)); });
  fireEvent.click(q.getByRole('button', { name: 'Pause focus' }));
  const paused = q.getByRole('timer').textContent;
  assert.equal(field.disabled, true);
  fireEvent.click(q.getByRole('button', { name: 'Resume focus' }));
  assert.equal(q.getByRole('timer').textContent, paused);
  fireEvent.click(q.getByRole('button', { name: 'Reset timer' }));
  assert.equal(field.disabled, false); assert.equal(field.value, '37');
  fireEvent.change(field, { target: { value: '180' } });
  fireEvent.click(q.getByRole('button', { name: 'Start focus' }));
  assert.equal(q.getByRole('timer').textContent, '180:00');
});

test('typed private and shared durations remain separate and a real peer receives an arbitrary 37 minute shared cycle', async t => {
  const dom = new JSDOM('<!doctype html><html><body></body></html>', { url: 'http://localhost' });
  Object.assign(globalThis, { window: dom.window, document: dom.window.document, HTMLElement: dom.window.HTMLElement, IS_REACT_ACT_ENVIRONMENT: true });
  const { render, fireEvent, within, waitFor, cleanup } = await import('@testing-library/react');
  const server = createStudyServer(), endpoint = await server.listen(0);
  t.after(async () => { cleanup(); await server.close(); dom.window.close(); });
  const a = render(<App endpoint={endpoint} />), b = render(<App endpoint={endpoint} />), q = within(a.container), r = within(b.container);
  fireEvent.change(q.getByRole('spinbutton', { name: 'Focus length' }), { target: { value: '53' } });
  for (const target of [q, r]) fireEvent.click(target.getByRole('button', { name: 'Party' }));
  await waitFor(() => assert.equal((q.getByRole('button', { name: 'Create room' }) as HTMLButtonElement).disabled, false));
  fireEvent.change(q.getByLabelText('Your name'), { target: { value: 'Synthetic first' } });
  fireEvent.click(q.getByRole('button', { name: 'Create room' }));
  await waitFor(() => assert.ok(q.getByLabelText('Room code')));
  fireEvent.change(r.getByLabelText('Your name'), { target: { value: 'Synthetic second' } });
  fireEvent.change(r.getByLabelText('Invite code'), { target: { value: q.getByLabelText('Room code').textContent } });
  fireEvent.click(r.getByRole('button', { name: 'Join room' }));
  await waitFor(() => assert.ok(r.getByLabelText('Room code')));
  for (const target of [q, r]) fireEvent.click(target.getByRole('button', { name: 'Join room cycle' }));
  const field = q.getByRole('spinbutton', { name: 'Focus length' }) as HTMLInputElement;
  fireEvent.change(field, { target: { value: '' } });
  await React.act(async () => { await new Promise(r => setTimeout(r, 350)); });
  assert.equal(field.value, ''); assert.equal(r.getByRole('timer').textContent, '25:00');
  fireEvent.change(field, { target: { value: '37' } });
  assert.equal(r.getByRole('timer').textContent, '25:00', 'typing alone is private, not a timer action');
  fireEvent.click(q.getByRole('button', { name: 'Start focus' }));
  await waitFor(() => assert.ok(r.getByRole('button', { name: 'Pause focus' })));
  await waitFor(() => assert.equal((r.getByRole('spinbutton', { name: 'Focus length' }) as HTMLInputElement).value, '37'));
  assert.equal(field.disabled, true);
  fireEvent.click(q.getByRole('button', { name: 'Keep personal clock' }));
  assert.equal((q.getByRole('spinbutton', { name: 'Focus length' }) as HTMLInputElement).value, '53');
  assert.equal(q.getByRole('timer').textContent, '53:00', 'returning to personal restores its unticked private preview');
  assert.ok(r.getByRole('button', { name: 'Pause focus' }));
  fireEvent.click(r.getByRole('button', { name: 'Pause focus' }));
  await waitFor(() => assert.ok(r.getByRole('button', { name: 'Resume focus' })));
  fireEvent.click(r.getByRole('button', { name: 'Reset timer' }));
  await waitFor(() => assert.ok(r.getByRole('button', { name: 'Start focus' })));
  fireEvent.click(q.getByRole('button', { name: 'Join room cycle' }));
  await waitFor(() => assert.equal((q.getByRole('spinbutton', { name: 'Focus length' }) as HTMLInputElement).disabled, false));
  fireEvent.change(r.getByRole('spinbutton', { name: 'Focus length' }), { target: { value: '81' } });
  fireEvent.click(q.getByRole('button', { name: 'Start focus' }));
  await waitFor(() => assert.ok(r.getByRole('button', { name: 'Pause focus' })));
  await waitFor(() => assert.equal((r.getByRole('spinbutton', { name: 'Focus length' }) as HTMLInputElement).value, '37', 'actual shared duration replaces an unsubmitted peer buffer even when durationMs is unchanged'));
});
