import { test } from 'node:test';
import assert from 'node:assert/strict';
import React from 'react';
import { JSDOM } from 'jsdom';
import { createStudyServer } from '../server/app.js';
import { App } from '../src/App.js';

test('two rendered clients operate the room while drafts remain private until explicit sharing', async t => {
  const dom = new JSDOM('<!doctype html><html><body></body></html>', { url: 'http://localhost' });
  Object.assign(globalThis, { window: dom.window, document: dom.window.document, HTMLElement: dom.window.HTMLElement, IS_REACT_ACT_ENVIRONMENT: true });
  const { render, fireEvent, waitFor, within, cleanup } = await import('@testing-library/react');
  const app = createStudyServer(); const endpoint = await app.listen(0);
  t.after(async () => { cleanup(); await app.close(); dom.window.close(); });
  const a = render(<App endpoint={endpoint} />);
  const b = render(<App endpoint={endpoint} />);
  const qa = within(a.container), qb = within(b.container);
  async function click(q: typeof qa, name: string) {
    await waitFor(() => assert.equal((q.getByRole('button', { name }) as HTMLButtonElement).disabled, false));
    fireEvent.click(q.getByRole('button', { name }));
  }
  fireEvent.change(qa.getByRole('spinbutton', { name: 'Focus length' }), { target: { value: '15' } });
  await click(qa, 'Start focus');
  await React.act(async () => { await new Promise(resolve => setTimeout(resolve, 1100)); });
  await click(qa, 'Pause focus');
  const personalClock = qa.getByRole('timer').textContent;
  fireEvent.change(qa.getByRole('textbox', { name: 'Your session intention' }), { target: { value: 'SYNTHETIC PRIVATE DRAFT' } });
  fireEvent.change(qb.getByRole('spinbutton', { name: 'Focus length' }), { target: { value: '45' } });
  await click(qb, 'Start focus');
  await click(qa, 'Party');
  await click(qb, 'Party');
  await waitFor(() => assert.equal((qa.getByRole('button', { name: 'Create room' }) as HTMLButtonElement).disabled, false));
  fireEvent.change(qa.getByRole('textbox', { name: 'Your name' }), { target: { value: 'Cedar' } });
  await click(qa, 'Create room');
  await waitFor(() => assert.ok(qa.getByLabelText('Room code')));
  const code = qa.getByLabelText('Room code').textContent!;
  assert.equal(qa.getByRole('timer').textContent, personalClock);
  assert.ok(qa.getByRole('button', { name: 'Keep personal clock' }));
  await click(qa, 'Join room cycle');
  assert.equal(qa.getByRole('timer').textContent, '25:00');
  fireEvent.change(qb.getByRole('textbox', { name: 'Your name' }), { target: { value: 'Fern' } });
  fireEvent.change(qb.getByRole('textbox', { name: 'Invite code' }), { target: { value: code } });
  await click(qb, 'Join room');
  await waitFor(() => assert.ok(qa.getByText('Fern')));
  await click(qb, 'Join room cycle');
  fireEvent.change(qa.getByRole('textbox', { name: 'Your session intention' }), { target: { value: 'SYNTHETIC PRIVATE DRAFT' } });
  assert.equal(b.container.textContent!.includes('SYNTHETIC PRIVATE DRAFT'), false);
  await click(qa, 'Share with room');
  await waitFor(() => assert.ok(qb.getByText('SYNTHETIC PRIVATE DRAFT')));
  await click(qa, 'Withdraw sharing');
  await waitFor(() => assert.equal(b.container.textContent!.includes('SYNTHETIC PRIVATE DRAFT'), false));
  assert.equal((qa.getByRole('textbox', { name: 'Your session intention' }) as HTMLTextAreaElement).value, 'SYNTHETIC PRIVATE DRAFT');
  await click(qa, 'Start focus');
  await waitFor(() => assert.ok(qb.getByRole('button', { name: 'Pause focus' })));
  await click(qb, 'Pause focus');
  await waitFor(() => assert.ok(qa.getByRole('button', { name: 'Resume focus' })));
  await click(qa, 'Reset timer');
  await waitFor(() => assert.ok(qb.getByRole('button', { name: 'Start focus' })));
  assert.equal(qa.getByRole('timer').textContent, '25:00');
  await click(qa, 'Share with room');
  await waitFor(() => assert.ok(qb.getByText('SYNTHETIC PRIVATE DRAFT')));
  await click(qa, 'Solo');
  assert.equal(qa.getByRole('timer').textContent, personalClock);
  assert.equal((qa.getByRole('textbox', { name: 'Your session intention' }) as HTMLTextAreaElement).value, 'SYNTHETIC PRIVATE DRAFT');
  await waitFor(() => assert.equal(!!qb.queryByText('Cedar'), false));
  assert.equal(b.container.textContent!.includes('SYNTHETIC PRIVATE DRAFT'), false);
  await click(qa, 'Party');
  await waitFor(() => assert.equal((qa.getByRole('button', { name: 'Join room' }) as HTMLButtonElement).disabled, false));
  fireEvent.change(qa.getByRole('textbox', { name: 'Invite code' }), { target: { value: code } });
  await click(qa, 'Join room');
  await waitFor(() => assert.ok(qb.getByText('Cedar')));
  assert.ok(qa.getByRole('button', { name: 'Keep personal clock' }));
  assert.equal(qa.getByRole('timer').textContent, personalClock);
  assert.equal(b.container.textContent!.includes('SYNTHETIC PRIVATE DRAFT'), false);
  // Leave while a real create acknowledgement is in flight: no late reply may resurrect Party.
  fireEvent.click(qa.getByRole('button', { name: 'Solo' }));
  fireEvent.click(qa.getByRole('button', { name: 'Party' }));
  await waitFor(() => assert.equal((qa.getByRole('button', { name: 'Create room' }) as HTMLButtonElement).disabled, false));
  fireEvent.click(qa.getByRole('button', { name: 'Create room' }));
  fireEvent.click(qa.getByRole('button', { name: 'Solo' }));
  await React.act(async () => { await new Promise(resolve => setTimeout(resolve, 100)); });
  assert.equal(qa.queryAllByRole('alert').length, 0);
  assert.equal(qa.queryAllByLabelText('Room code').length, 0);
  assert.equal(qa.getByRole('timer').textContent, personalClock);
  await click(qb, 'Solo');
  assert.ok(qb.getByRole('heading', { name: 'Personal focus' }));
  assert.ok(qb.getByRole('button', { name: 'Pause focus' }), 'a running private clock continues independently during shared timer resets');
  assert.equal((qb.getByRole('spinbutton', { name: 'Focus length' }) as HTMLInputElement).value, '45');
});
